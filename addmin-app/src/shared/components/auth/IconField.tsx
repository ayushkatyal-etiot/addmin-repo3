import { InputHTMLAttributes, ReactNode, useState } from "react";

// Icon-prefixed input row used across every auth form (email, password).
// `type="password"` gets an eye-toggle button for free, matching the
// show/hide affordance on every password field in Login Flow.dc.html.
export function IconField({
  icon,
  className = "",
  ...props
}: { icon: ReactNode } & InputHTMLAttributes<HTMLInputElement>) {
  const [revealed, setRevealed] = useState(false);
  const isPassword = props.type === "password";

  return (
    <div className={`auth-field ${className}`}>
      <span className="auth-field-icon">{icon}</span>
      <input {...props} type={isPassword && revealed ? "text" : props.type} />
      {isPassword && (
        <button
          type="button"
          onClick={() => setRevealed((r) => !r)}
          aria-label={revealed ? "Hide password" : "Show password"}
          className="auth-field-toggle"
        >
          {revealed ? <EyeOffIcon /> : <EyeIcon />}
        </button>
      )}
    </div>
  );
}

